"""Build a small Newton-only inertia overlay; requires usd-core and numpy.

Masses (kg): ros-industrial-attic/robotiq kinetic-devel,
robotiq_2f_85_gripper_visualization/urdf/robotiq_arg2f{,_85_model_macro}.xacro.
These legacy CAD values are starting estimates, not calibrated hardware data.
Inertia uses uniform local collision bounding boxes, avoiding assumptions about
URDF-to-USD link frames. All geometry and joints come from the original asset.
"""

from pathlib import Path

import numpy as np
from pxr import Gf, Sdf, Usd, UsdGeom, UsdPhysics

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "assets/robots/franka_robotiq_2f_85_isaac60.usd"
TARGET = SOURCE.with_name("franka_robotiq_2f_85_newton.usda")
MASSES = {
    "base_link": 0.22652,
    "outer_knuckle": 0.00853198276973456,
    "outer_finger": 0.022614240507152,
    "inner_knuckle": 0.0271177346495152,
    "inner_finger": 0.0104003125914103,
}


def build():
    source = Usd.Stage.Open(str(SOURCE))
    stage = Usd.Stage.CreateInMemory()
    # Resolve the source for the in-memory stage through an absolute path while
    # building, then restore the portable sibling reference before export.
    stage.GetRootLayer().subLayerPaths = [str(SOURCE)]
    stage.SetDefaultPrim(stage.GetPrimAtPath("/panda"))
    stage.GetRootLayer().comment = (
        "Experimental Newton inertia overlay. Generated by scripts/build_newton_asset.py. "
        "Robotiq CAD masses; uniform local collision-box inertia estimates."
    )
    cache = UsdGeom.BBoxCache(Usd.TimeCode.Default(), [UsdGeom.Tokens.default_], useExtentsHint=False)
    for body in source.Traverse():
        if not str(body.GetPath()).startswith("/panda/") or not body.HasAPI(UsdPhysics.RigidBodyAPI):
            continue
        mass_api = UsdPhysics.MassAPI(body)
        mass = mass_api.GetMassAttr().Get() if mass_api else None
        inertia = mass_api.GetDiagonalInertiaAttr().Get() if mass_api else None
        dest = stage.OverridePrim(body.GetPath())
        api = UsdPhysics.MassAPI.Apply(dest)
        axes = mass_api.GetPrincipalAxesAttr().Get() if mass_api else None
        if axes is None or axes.GetLength() < 1e-6:
            api.CreatePrincipalAxesAttr(Gf.Quatf(1))
        if mass and inertia is not None and min(inertia) > 0:
            continue
        name = body.GetName().removeprefix("left_").removeprefix("right_")
        mass = mass or MASSES.get(name)
        if mass is None:
            raise ValueError(f"Missing documented mass for {body.GetPath()}")
        bounds = Gf.Range3d()
        for prim in Usd.PrimRange(body, Usd.TraverseInstanceProxies()):
            if prim.HasAPI(UsdPhysics.CollisionAPI):
                bounds.UnionWith(cache.ComputeRelativeBound(prim, body).ComputeAlignedRange())
        if bounds.IsEmpty():
            raise ValueError(f"No collision bounds for {body.GetPath()}")
        size = np.asarray(bounds.GetSize())
        if not np.isfinite(size).all() or min(size) <= 0:
            raise ValueError(f"Invalid collision bounds for {body.GetPath()}: {size}")
        diagonal = mass / 12 * (np.sum(size ** 2) - size ** 2)
        api.CreateMassAttr(float(mass))
        api.CreateCenterOfMassAttr(Gf.Vec3f(*bounds.GetMidpoint()))
        api.CreateDiagonalInertiaAttr(Gf.Vec3f(*diagonal))
        api.CreatePrincipalAxesAttr(Gf.Quatf(1))
        print(body.GetPath(), "mass=", mass, "box=", size, "inertia=", diagonal)
    output = Sdf.Layer.CreateAnonymous()
    output.TransferContent(stage.GetRootLayer())
    output.subLayerPaths = [SOURCE.name]
    output.Export(str(TARGET))


if __name__ == "__main__":
    build()
