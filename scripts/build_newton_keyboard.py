"""Compile HOT3D keyboard components into convex colliders without CoACD.

Preserves each authored component's exterior and the gaps between keys. Only
open keycap bottoms are closed. Original visuals and mass properties remain.
"""
import argparse
import hashlib
import importlib.util
import json
from pathlib import Path

import numpy as np
from scipy.spatial import ConvexHull

ROOT = Path(__file__).resolve().parents[1]
SOURCE_SHA256 = 'f883230318e4c79c92f0eb35ae5523d49f6922e75f16898f395ea4c50532fa71'
MESH_NAME = 'obj_000028_Mesh'


def source_components(source):
    from pxr import Usd, UsdGeom
    from newton import Mesh
    from newton._src.usd.utils import fan_triangulate_faces
    from newton._src.utils.mesh import split_mesh_components

    if hashlib.sha256(source.read_bytes()).hexdigest() != SOURCE_SHA256:
        raise ValueError('Keyboard source changed; review geometry before rebaking')
    stage = Usd.Stage.Open(str(source))
    meshes = [UsdGeom.Mesh(p) for p in stage.Traverse() if p.IsA(UsdGeom.Mesh)]
    if len(meshes) != 1 or meshes[0].GetPrim().GetName() != MESH_NAME:
        raise ValueError('Keyboard mesh topology changed')
    mesh = meshes[0]
    vertices = np.asarray(mesh.GetPointsAttr().Get())
    faces = fan_triangulate_faces(np.array(mesh.GetFaceVertexCountsAttr().Get()),
                                  np.array(mesh.GetFaceVertexIndicesAttr().Get())).reshape(-1, 3)
    components = split_mesh_components(Mesh(vertices, faces, compute_inertia=False))
    if len(components) != 110:
        raise ValueError('Keyboard component topology changed')
    return vertices, faces, components


def compile_component(vertices, faces):
    """Require original triangles on hull boundary; close only keycap bottoms."""
    vertices = np.asarray(vertices, dtype=float)
    faces = np.asarray(faces).reshape(-1, 3)
    hull = ConvexHull(vertices)
    distances = vertices[faces].mean(1) @ hull.equations[:, :3].T + hull.equations[:, 3]
    inset = float(np.max(np.abs(distances.max(1))))
    if inset > 2e-7:
        raise ValueError(f'Non-convex source contact surface: {inset} m')
    # Allow 0.5 micrometre for float32 source triangulation slivers.
    # Every hull plane must be represented by an authored triangle, except
    # the missing bottom of an open keycap (local Y=0, outward normal -Y).
    tris = vertices[faces]
    for plane in hull.equations:
        authored = np.any(np.all(np.abs(tris @ plane[:3] + plane[3]) < 5e-7, axis=1))
        bottom = np.allclose(plane[:3], [0., -1., 0.], atol=1e-6) and abs(plane[3]) < 2e-7
        if not authored and not bottom:
            raise ValueError('Hull would introduce a non-bottom contact surface')
    ids = np.unique(hull.simplices)
    inverse = np.full(len(vertices), -1)
    inverse[ids] = np.arange(len(ids))
    out_faces = inverse[hull.simplices]
    out_vertices = vertices[ids]
    tri = out_vertices[out_faces]
    normals = np.cross(tri[:, 1]-tri[:, 0], tri[:, 2]-tri[:, 0])
    inward = np.einsum('ij,ij->i', normals, tri.mean(1)-out_vertices.mean(0)) < 0
    out_faces[inward] = out_faces[inward][:, [0, 2, 1]]
    if len(out_vertices) > 64 or not np.allclose(out_vertices.min(0), vertices.min(0), atol=1e-9) or not np.allclose(out_vertices.max(0), vertices.max(0), atol=1e-9):
        raise ValueError('Compiled component changed bounds or exceeded vertex budget')
    return out_vertices, out_faces, inset


def main():
    from pxr import Usd, UsdGeom, UsdPhysics, Vt
    from robolab.core.utils.newton_compiled_colliders import geometry_key, load_colliders
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--repo', type=Path, default=ROOT)
    p.add_argument('--output', type=Path)
    args = p.parse_args()
    source = args.repo / 'assets/objects/hot3d/keyboard.usd'
    output = args.output or source.with_name('keyboard_colliders.usda')
    vertices, faces, components = source_components(source)
    stage = Usd.Stage.CreateInMemory()
    root = UsdGeom.Xform.Define(stage, '/KeyboardColliders')
    stage.SetDefaultPrim(root.GetPrim())
    UsdGeom.SetStageUpAxis(stage, UsdGeom.Tokens.y)
    UsdGeom.SetStageMetersPerUnit(stage, 1.)
    stage.GetRootLayer().documentation = (
        'Derived from HOT3D Model Data, copyright Meta Platforms Technologies, LLC. '
        'CC BY-SA 4.0 with additional HOT3D non-sale restriction; see LICENSE in this directory. '
        'Generated by scripts/build_newton_keyboard.py. Collision library in source mesh coordinates; '
        'original asset supplies transforms, visuals, materials and body mass properties. '
        '110 component hulls; only open keycap bottoms are closed.')
    entry = dict(source_geometry_sha256=geometry_key(vertices, faces), source_component_count=len(components),
                 part_count=len(components), paths=[])
    max_inset = 0.
    for i, (v, f) in enumerate(components):
        v, f, inset = compile_component(v, f)
        max_inset = max(max_inset, inset)
        path = f'/KeyboardColliders/component_{i:03d}'
        mesh = UsdGeom.Mesh.Define(stage, path)
        mesh.CreatePointsAttr(Vt.Vec3fArray.FromNumpy(v.astype(np.float32)))
        mesh.CreateFaceVertexCountsAttr([3]*len(f))
        mesh.CreateFaceVertexIndicesAttr(f.ravel().tolist())
        mesh.CreateSubdivisionSchemeAttr(UsdGeom.Tokens.none)
        UsdPhysics.CollisionAPI.Apply(mesh.GetPrim()).CreateCollisionEnabledAttr(True)
        UsdPhysics.MeshCollisionAPI.Apply(mesh.GetPrim()).CreateApproximationAttr('convexHull')
        entry['paths'].append(path)
    manifest = dict(format_version=2, source_asset_sha256=SOURCE_SHA256, max_validated_scale=1.,
                    newton='1.5.2', part_count=len(components), meshes={MESH_NAME:entry},
                    max_source_face_hull_inset_m=max_inset,
                    approximations=['Close open keycap bottoms; retain separate key hulls and exterior contact surfaces'])
    stage.GetRootLayer().Export(str(output))
    manifest['collision_asset_sha256'] = hashlib.sha256(output.read_bytes()).hexdigest()
    output.with_suffix('.json').write_text(json.dumps(manifest, indent=2, sort_keys=True)+'\n')
    load_colliders(output, mesh_names={MESH_NAME}, max_parts=128, asset_name='keyboard')
    print(json.dumps(dict(parts=110, max_source_face_hull_inset_m=max_inset, bytes=output.stat().st_size)))


if __name__ == '__main__':
    main()
